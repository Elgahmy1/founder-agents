"""Metrics computed only from the committed decision_log.json (no model call, no network).

    python evals/run_metrics.py            # prints the report
    python evals/run_metrics.py --write    # writes evals/run_metrics.md

Every number below is counted from log entries, so it can be checked by hand
against decision_log.json.
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "decision_log.json"
OUT = ROOT / "evals" / "run_metrics.md"


def _t(ts: str) -> datetime:
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ")


def approval_audit(entries: list[dict]) -> dict:
    """Every executed action must follow a founder approval of the same item."""
    approved, executed, unapproved = set(), 0, []
    for e in entries:
        item = e.get("item_id")
        if e["agent"] == "founder" and e["action"].startswith("approve_") and item:
            approved.add(item)
        elif e["agent"] == "executor":
            executed += 1
            if e.get("approved_by") != "founder" or (item and item not in approved):
                unapproved.append(e["action"])
    requested = sum(1 for e in entries if e["agent"] == "approval" and e["action"].startswith("request_"))
    return {"requested": requested, "approved": len(approved), "executed": executed, "unapproved": unapproved}


def per_run(entries: list[dict]) -> dict[str, dict]:
    runs: dict[str, dict] = defaultdict(lambda: {"idea": "", "calls": 0, "tokens": 0, "cost": 0.0, "models": Counter(),
                                                 "times": [], "gates": [], "decisions": [], "phases": set(),
                                                 "sandbox": [], "sources": set(), "policy_stop": None})
    for e in entries:
        if not e.get("run_id"):
            continue  # log-wide entries (no run) are not per-run metrics
        r = runs[e["run_id"]]
        r["times"].append(_t(e["timestamp"]))
        r["cost"] += float(e.get("cost") or 0)
        r["sources"].update(e.get("sources") or [])
        if e.get("phase"):
            r["phases"].add(e["phase"])
        if e["action"] == "start_run":
            r["idea"] = e.get("detail") or ""
        if e.get("model"):
            r["calls"] += 1
            r["tokens"] += int(e.get("tokens") or 0)
            r["models"][e["model"]] += 1
        if e["agent"] == "gate":
            r["gates"].append((e.get("phase"), e["action"], e.get("outcome")))
        if e["agent"] == "founder" and e["action"].endswith("_gate_decision"):
            r["decisions"].append((e["action"].removesuffix("_decision"), e.get("recommendation"), e.get("outcome"),
                                   bool(e.get("founder_override"))))
        if e["action"] == "screen_brief" and e.get("outcome") == "stop":
            r["policy_stop"] = e.get("detail")
        if e["action"] == "run_acceptance_checks":
            r["sandbox"].append((e["timestamp"], e.get("detail") or ""))
    return runs


def report(entries: list[dict]) -> str:
    runs = per_run(entries)
    audit = approval_audit(entries)
    total_calls = sum(r["calls"] for r in runs.values())
    total_tokens = sum(r["tokens"] for r in runs.values())
    decisions = [d for r in runs.values() for d in r["decisions"]]
    overrides = [d for d in decisions if d[3]]
    final = Counter()
    for r in runs.values():
        if r["policy_stop"]:
            final["stop (policy screen)"] += 1
        elif r["decisions"]:
            final[r["decisions"][-1][2]] += 1

    lines = [
        "# Run metrics (computed from decision_log.json)", "",
        f"Generated by `python evals/run_metrics.py --write` from {len(entries)} log entries. No model call; "
        "every figure is a count over the committed log.", "",
        "## Summary", "",
        "| Metric | Value |", "|---|---|",
        f"| Runs in the log | {len(runs)} |",
        f"| Model calls | {total_calls} |",
        f"| Tokens | {total_tokens:,} |",
        f"| Cost (USD) | ${sum(r['cost'] for r in runs.values()):.2f} |",
        f"| Gate recommendations computed | {sum(len(r['gates']) for r in runs.values())} |",
        f"| Founder gate decisions | {len(decisions)} |",
        f"| Founder overrides of a recommendation | {len(overrides)} |",
        f"| Runs ending in stop | {sum(v for k, v in final.items() if k.startswith('stop'))} of {len(runs)} |",
        f"| Approval requests (publish / send / sign) | {audit['requested']} |",
        f"| Actions executed | {audit['executed']} |",
        f"| Actions executed without a founder approval of the same item | {len(audit['unapproved'])} |",
        "",
        "## Per run", "",
        "| Run | Idea | Model calls | Tokens | Cost | Wall time | Phases reached | Distinct cited source URLs | Ended |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for rid, r in sorted(runs.items(), key=lambda kv: min(kv[1]["times"])):
        wall = max(r["times"]) - min(r["times"])
        ended = ("stop (policy screen)" if r["policy_stop"] else
                 (r["decisions"][-1][2] if r["decisions"] else "waiting at a gate"))
        phases = f"{max(r['phases'])}" if r["phases"] else ("0" if r["policy_stop"] else "1")
        idea = (r["idea"][:70] + "...") if len(r["idea"]) > 70 else r["idea"]
        lines.append(f"| `{rid}` | {idea} | {r['calls']} | {r['tokens']:,} | ${r['cost']:.2f} | "
                     f"{int(wall.total_seconds() // 60)} min | {phases} | {len(r['sources'])} | {ended} |")
    lines += ["", "Wall time includes the time the run waited for the founder at gates and approvals.", "",
              "## Gate recommendations vs founder decisions", "",
              "| Run | Gate | System recommended | Founder decided | Override |", "|---|---|---|---|---|"]
    for rid, r in sorted(runs.items(), key=lambda kv: min(kv[1]["times"])):
        for gate, rec, dec, ov in r["decisions"]:
            lines.append(f"| `{rid}` | {gate.replace('_', ' ')} | {rec} | {dec} | {'yes' if ov else 'no'} |")
    lines += ["", "## Sandbox runs of generated code", "",
              "Each attempt is one generation (attempt 1) or its repair (attempt 2), checked against the story's acceptance criteria.", "",
              "| Run | Time (UTC) | Result |", "|---|---|---|"]
    for rid, r in runs.items():
        for ts, d in r["sandbox"]:
            lines.append(f"| `{rid}` | {ts[:16].replace('T', ' ')} | {d.split(';')[0]} |")
    models = Counter()
    for r in runs.values():
        models.update(r["models"])
    lines += ["", "## Models used", "", "| Model | Calls |", "|---|---|",
              *[f"| `{m}` | {n} |" for m, n in models.most_common()]]
    return "\n".join(lines) + "\n"


def main() -> int:
    entries = json.loads(LOG.read_text(encoding="utf-8"))
    md = report(entries)
    if "--write" in sys.argv:
        OUT.write_text(md, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
