"""Cross-artifact consistency audit (deterministic, no model, CI-checked).

Checks that what one phase says agrees with what another phase recorded:
1. Phase 6 never counts MOCKED events as real traction: every Phase 6 line about paid orders, checkout or the
   waitlist that reports a non-zero figure must also say it is MOCKED / entered by the founder / not used.
2. Code-enforced caps hold in the saved outputs: an area check whose fit is not UNKNOWN cites at least one
   source, and a co-founder verdict is never more positive than its gate's recommendation.
3. Every acceptance criterion listed as DEFERRED in Phase 3's code output is disclosed in the user guide.

Usage: python evals/consistency_audit.py [--write]   (exit 1 on any violation; --write updates the report)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"
RANK = {"go": 3, "repeat": 2, "pivot": 1, "stop": 0}
VERDICT_MAX = {"strong": 3, "promising": 2, "weak": 1, "do not pursue": 0}
MOCK_TOPIC = re.compile(r"paid orders?|checkout|test[- ]mode|waitlist|sales?\b", re.I)
HONEST = re.compile(r"MOCKED|entered by the founder|not used|reported, not|founder-reported|\b0\b", re.I)


def audit(out: Path = OUT) -> list[str]:
    problems: list[str] = []
    for f in sorted(out.glob("phase6_*")):
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if MOCK_TOPIC.search(line) and re.search(r"\b[1-9]\d*\b", line) and not HONEST.search(line):
                problems.append(f"{f.name}:{n}: reports MOCKED activity as a figure without saying so")
    for f in sorted(out.glob("phase1_step0_area_check-*")):
        t = f.read_text(encoding="utf-8")
        m = re.search(r"\*\*Local fit: (\w+)\.\*\*", t)
        if m and m.group(1).upper() != "UNKNOWN" and "[source:" not in t:
            problems.append(f"{f.name}: fit {m.group(1)} without any sourced claim (must be UNKNOWN)")
    for f in sorted(out.glob("phase1_step4_cofounder_verdict-*")):
        m = re.search(r"\*\*Verdict: ([A-Z ]+)\.\*\*", f.read_text(encoding="utf-8"))
        gate = out / f.name.replace("phase1_step4_cofounder_verdict", "phase1_gate_decision")
        g = re.search(r"System recommendation: (\w+)", gate.read_text(encoding="utf-8")) if gate.exists() else None
        if m and g and VERDICT_MAX.get(m.group(1).strip().lower(), 0) > RANK.get(g.group(1).lower(), 3):
            problems.append(f"{f.name}: verdict {m.group(1).strip()} is more positive than the gate's {g.group(1)}")
    for f in sorted(out.glob("phase3_step4_code-*")):
        guide = out / f.name.replace("phase3_step4_code", "phase3_step6_user_guide")
        deferred = {re.sub(r"\s+", " ", c.strip())[:60] for c in
                    re.findall(r"^\| US\d+ \| (.+?) \| - \| DEFERRED", f.read_text(encoding="utf-8"), re.M)}
        if deferred and not guide.exists():
            problems.append(f"{f.name}: {len(deferred)} DEFERRED criteria but no user guide discloses them")
        elif deferred:
            g = re.sub(r"\s+", " ", guide.read_text(encoding="utf-8"))
            for c in deferred:
                if c not in g:
                    problems.append(f"{guide.name}: DEFERRED criterion not disclosed: {c}...")
    return problems


def main() -> int:
    problems = audit()
    n6 = len(list(OUT.glob("phase6_*")))
    n3 = len(list(OUT.glob("phase3_step4_code-*")))
    nv = len(list(OUT.glob("phase1_step4_cofounder_verdict-*"))) + len(list(OUT.glob("phase1_step0_area_check-*")))
    md = ["# Cross-artifact consistency audit", "",
          "Generated by `python evals/consistency_audit.py --write`; CI fails if any check fails.", "",
          f"- Phase 6 files checked for MOCKED activity reported as traction: {n6}",
          f"- Area checks and co-founder verdicts checked against their code-enforced caps: {nv}",
          f"- Phase 3 code outputs whose DEFERRED criteria must be disclosed in the user guide: {n3}",
          f"- Violations: {len(problems)}", ""] + [f"- {p}" for p in problems]
    if "--write" in sys.argv:
        (ROOT / "evals" / "consistency_audit.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
