"""Audit of the market claims in outputs/ against the committed decision_log.json (no model call, no network).

    python evals/claims_audit.py            # prints the report
    python evals/claims_audit.py --write    # writes evals/claims_audit.md

For every Markdown output it counts the claims that cite a source and the claims
labelled ASSUMPTION, and checks that every cited URL is one the research tools
actually retrieved during a run: it must appear in the `sources` of a logged
agent action. A URL that no logged action retrieved is reported as unretrieved,
which would mean a model invented or altered a citation.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "decision_log.json"
OUTPUTS = ROOT / "outputs"
OUT = ROOT / "evals" / "claims_audit.md"
URL = re.compile(r"https?://[^\s)\]>|`\"']+")
SOURCED = re.compile(r"\[source: (https?://[^\]\s]+)\]")


def retrieved(entries: list[dict]) -> set[str]:
    return {u for e in entries for u in (e.get("sources") or [])}


def audit_file(text: str, known: set[str]) -> dict:
    urls = {u.rstrip(".,;") for u in URL.findall(text)}
    return {"sourced": len(SOURCED.findall(text)), "assumption": text.count("ASSUMPTION"),
            "urls": len(urls), "unretrieved": sorted(u for u in urls if u not in known)}


def audit(entries: list[dict], files: dict[str, str]) -> dict[str, dict]:
    known = retrieved(entries)
    return {name: audit_file(text, known) for name, text in sorted(files.items())}


def report(entries: list[dict], files: dict[str, str]) -> str:
    rows = audit(entries, files)
    rows = {k: v for k, v in rows.items() if v["sourced"] or v["assumption"] or v["urls"]}
    tot = {k: sum(r[k] for r in rows.values()) for k in ("sourced", "assumption", "urls")}
    bad = sorted({u for r in rows.values() for u in r["unretrieved"]})
    lines = [
        "# Claims audit (computed from outputs/ and decision_log.json)", "",
        "Generated by `python evals/claims_audit.py --write`. No model call; every figure is a count over committed "
        "files. A cited URL counts as retrieved only if it is in the `sources` of an action in the decision log.", "",
        "## Summary", "", "| Metric | Value |", "|---|---|",
        f"| Output files with claims or links | {len(rows)} |",
        f"| Claims citing a source (`[source: URL]`) | {tot['sourced']} |",
        f"| Claims or items labelled ASSUMPTION | {tot['assumption']} |",
        f"| Distinct cited URLs (counted per file) | {tot['urls']} |",
        f"| Cited URLs that no logged action retrieved | {len(bad)} |", "",
        "## Per file", "", "| Output | Sourced claims | ASSUMPTION labels | Cited URLs | Unretrieved |",
        "|---|---|---|---|---|",
        *[f"| `{n}` | {r['sourced']} | {r['assumption']} | {r['urls']} | {len(r['unretrieved'])} |" for n, r in rows.items()],
    ]
    if bad:
        lines += ["", "## Unretrieved URLs", "", *[f"- {u}" for u in bad]]
    return "\n".join(lines) + "\n"


def load() -> tuple[list[dict], dict[str, str]]:
    entries = json.loads(LOG.read_text(encoding="utf-8"))
    files = {p.name: p.read_text(encoding="utf-8") for p in OUTPUTS.glob("*.md")}
    return entries, files


def main() -> int:
    md = report(*load())
    if "--write" in sys.argv:
        OUT.write_text(md, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
